import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contractPath = resolve(repositoryRoot, "contracts/openapi/engineering-fixture.v1.json");
const outputPath = resolve(
  repositoryRoot,
  "src/frontend/packages/api-client/src/generated/engineering-fixture.ts",
);

function schemaType(schema) {
  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => schemaType({ ...schema, type })).join(" | ");
  }

  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }

  switch (schema.type) {
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `Array<${schemaType(schema.items ?? {})}>`;
    case "object":
      return "Record<string, unknown>";
    default:
      return "string";
  }
}

function renderInterface(name, schema) {
  const required = new Set(schema.required ?? []);
  const fields = Object.entries(schema.properties ?? {}).map(
    ([property, propertySchema]) =>
      `  ${property}${required.has(property) ? "" : "?"}: ${schemaType(propertySchema)};`,
  );
  return `export interface ${name} {\n${fields.join("\n")}\n}`;
}

export function renderGeneratedClient(contract) {
  const operationIds = Object.values(contract.paths).flatMap((path) =>
    Object.values(path).map((operation) => operation.operationId),
  );
  const requiredOperations = [
    "incrementEngineeringProbe",
    "getEngineeringProbeProjection",
    "rebuildEngineeringProbeProjection",
    "getEngineeringOperation",
    "cancelEngineeringOperation",
    "listEngineeringQuarantine",
    "retryEngineeringQuarantine",
    "retryEngineeringOutbox",
  ];
  for (const operationId of requiredOperations) {
    if (!operationIds.includes(operationId)) {
      throw new Error(`OpenAPI operation '${operationId}' is required by code generation.`);
    }
  }

  const interfaces = Object.entries(contract.components.schemas)
    .map(([name, schema]) => renderInterface(name, schema))
    .join("\n\n");

  return `// Generated by eng/generate-contracts.mjs from contracts/openapi/engineering-fixture.v1.json.
// Do not edit this file by hand.

${interfaces}

export interface EngineeringCommandHeaders {
  expectedVersion: number;
  idempotencyKey: string;
  correlationId?: string;
  commandDeadline?: string;
}

export type FetchLike = (input: RequestInfo | URL, init?: RequestInit) => Promise<Response>;

export class EngineeringFixtureClient {
  public constructor(
    private readonly baseUrl: string,
    private readonly fetcher: FetchLike = fetch,
  ) {}

  public incrementEngineeringProbe(
    probeId: string,
    request: IncrementProbeRequest,
    headers: EngineeringCommandHeaders,
    signal?: AbortSignal,
  ): Promise<IncrementProbeResponse> {
    return this.request<IncrementProbeResponse>(
      \`/platform/probes/\${encodeURIComponent(probeId)}/increments\`,
      {
        method: "POST",
        body: JSON.stringify(request),
        headers: {
          "Content-Type": "application/json",
          "If-Match": \`"\${headers.expectedVersion}"\`,
          "Idempotency-Key": headers.idempotencyKey,
          ...(headers.correlationId ? { "X-Correlation-ID": headers.correlationId } : {}),
          ...(headers.commandDeadline
            ? { "X-Command-Deadline": headers.commandDeadline }
            : {}),
        },
        ...(signal ? { signal } : {}),
      },
    );
  }

  public getEngineeringProbeProjection(
    probeId: string,
    signal?: AbortSignal,
  ): Promise<ProbeProjectionResponse> {
    return this.request<ProbeProjectionResponse>(
      \`/platform/probes/\${encodeURIComponent(probeId)}/projection\`,
      { ...(signal ? { signal } : {}) },
    );
  }

  public rebuildEngineeringProbeProjection(signal?: AbortSignal): Promise<OperationResponse> {
    return this.request<OperationResponse>("/platform/projections/probes/rebuild", {
      method: "POST",
      ...(signal ? { signal } : {}),
    });
  }

  public getEngineeringOperation(
    operationId: string,
    signal?: AbortSignal,
  ): Promise<OperationResponse> {
    return this.request<OperationResponse>(
      \`/platform/operations/\${encodeURIComponent(operationId)}\`,
      { ...(signal ? { signal } : {}) },
    );
  }

  public cancelEngineeringOperation(
    operationId: string,
    signal?: AbortSignal,
  ): Promise<void> {
    return this.requestVoid(
      \`/platform/operations/\${encodeURIComponent(operationId)}\`,
      { method: "DELETE", ...(signal ? { signal } : {}) },
    );
  }

  public listEngineeringQuarantine(signal?: AbortSignal): Promise<Array<QuarantineResponse>> {
    return this.request<Array<QuarantineResponse>>("/platform/quarantine", {
      ...(signal ? { signal } : {}),
    });
  }

  public retryEngineeringQuarantine(
    quarantineId: string,
    signal?: AbortSignal,
  ): Promise<void> {
    return this.requestVoid(
      \`/platform/quarantine/\${encodeURIComponent(quarantineId)}/retry\`,
      { method: "POST", ...(signal ? { signal } : {}) },
    );
  }

  public retryEngineeringOutbox(messageId: string, signal?: AbortSignal): Promise<void> {
    return this.requestVoid(
      \`/platform/outbox/\${encodeURIComponent(messageId)}/retry\`,
      { method: "POST", ...(signal ? { signal } : {}) },
    );
  }

  private async request<T>(path: string, init: RequestInit): Promise<T> {
    const response = await this.fetcher(\`\${this.baseUrl}\${path}\`, init);
    if (!response.ok) {
      throw (await response.json()) as ProblemDetails;
    }
    return (await response.json()) as T;
  }

  private async requestVoid(path: string, init: RequestInit): Promise<void> {
    const response = await this.fetcher(\`\${this.baseUrl}\${path}\`, init);
    if (!response.ok) {
      throw (await response.json()) as ProblemDetails;
    }
  }
}
`;
}

export async function generateContracts() {
  const contract = JSON.parse(await readFile(contractPath, "utf8"));
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, renderGeneratedClient(contract), "utf8");
  console.log(`Generated ${outputPath}`);
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  await generateContracts();
}
